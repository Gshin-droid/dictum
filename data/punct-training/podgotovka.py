# -*- coding: utf-8 -*-
"""Готовит учебный материал для своего разметчика знаков препинания.

На выходе — очищенные фразы **со знаками** и пометкой языка, а не готовые метки
для обучения. Так сделано намеренно: метки привязаны к разбивщику на подслова,
а разбивщик выбирается вместе с основанием модели. Нарезав метки сейчас, мы бы
зафиксировали выбор, который ещё не сделан.

    python podgotovka.py            # обычный прогон
    python podgotovka.py --selftest # проверка правил очистки
"""

import argparse
import json
import random
import re
import sys
import unicodedata
from collections import Counter
from pathlib import Path

ЗДЕСЬ = Path(__file__).resolve().parent
СЫРЬЁ = ЗДЕСЬ / "syroy"
ГОТОВО = ЗДЕСЬ / "gotovo"

# Алфавит модели распознавания: 71 знак из multilingual_vocab.txt. Учить
# разметчика на буквах, которых распознавание не выдаёт, бессмысленно — он
# будет ставить знаки вокруг того, чего никогда не увидит.
БУКВЫ = set("abcdefghijklmnopqrstuvwxyz"
            "абвгдежзийклмнопрстуфхцчшщъыьэюяё"
            "іғқңүұһәө'")
# Знаки, которые разметчик будет предсказывать. Всё остальное — кавычки, скобки,
# тире, многоточия — вычищается: модель их не ставит, и в эталоне им делать нечего.
ЗНАКИ = set(".,!?;:")
ДЕФИС = "-"
РАЗРЕШЕНО = БУКВЫ | ЗНАКИ | {ДЕФИС, " "}

МИН_СЛОВ, МАКС_СЛОВ = 4, 40
ДОЛЯ = {"kk": 0.45, "ru": 0.45, "en": 0.10}
НАБОРЫ = {
    "kk": "kaz_newscrawl_2016_300K",
    "ru": "rus_news_2020_300K",
    "en": "eng_news_2020_300K",
}
# Кириллица у казахского и русского, латиница у английского. Порог не 100 %:
# в новостях попадаются вкрапления, и выбрасывать из-за одного слова всю фразу
# расточительно.
ПИСЬМЕННОСТЬ = {"kk": "cyr", "ru": "cyr", "en": "lat"}
ПОРОГ_ПИСЬМЕННОСТИ = 0.8

КИРИЛЛИЦА = re.compile(r"[а-яёіғқңүұһәө]", re.IGNORECASE)
ЛАТИНИЦА = re.compile(r"[a-z]", re.IGNORECASE)
ЦИФРА = re.compile(r"[0-9]")
# Знаки, которые заменяем, а не выбрасываем фразу: типографика и переносы.
ЗАМЕНЫ = {
    "­": "", "​": "", "﻿": "",       # мягкий перенос и невидимки
    "«": "", "»": "", "“": "", "”": "", "„": "", "‟": "", '"': "",
    "‘": "'", "’": "'", "‚": "", "”": "",
    "–": "", "—": "", "―": "", "‑": "-", "‒": "-",  # тире убираем, дефисы оставляем
    "…": ".", "…": ".",
    "(": "", ")": "", "[": "", "]": "", "{": "", "}": "",
    "/": " ", "\\": " ", "|": " ", "*": "", "#": "", "&": " ", "%": "", "@": " ",
    "+": " ", "=": " ", "_": " ", "~": "", "^": "", "<": "", ">": "",
    "№": "", "§": "", "©": "", "®": "", "™": "",
}


# Буквы, неотличимые на вид. В казахских текстах поголовно встречается латинская
# «i» вместо кириллической «і»: «желi» вместо «желі». Выбросить такие фразы —
# значит выбить из набора самую частую казахскую букву, поэтому их чиним.
ОМОГЛИФЫ_В_КИРИЛЛИЦУ = str.maketrans({
    "a": "а", "c": "с", "e": "е", "i": "і", "o": "о", "p": "р", "x": "х", "y": "у",
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К", "M": "М",
    "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
})
ОМОГЛИФЫ_В_ЛАТИНИЦУ = str.maketrans({
    "а": "a", "с": "c", "е": "e", "і": "i", "о": "o", "р": "p", "х": "x", "у": "y",
    "А": "A", "В": "B", "С": "C", "Е": "E", "Н": "H", "К": "K", "М": "M",
    "О": "O", "Р": "P", "Т": "T", "Х": "X", "У": "Y",
})


def починить_омоглифы(слово: str) -> str:
    """Слово из двух письменностей — в одну, если различие только на вид.

    Чинится только меньшинство: в слове из кириллицы с одной латинской буквой
    правится буква, а не всё слово. Если после правки письменность так и не
    стала одной — слово испорчено по-настоящему, и решает это уже вызывающий.
    """
    кир, лат = len(КИРИЛЛИЦА.findall(слово)), len(ЛАТИНИЦА.findall(слово))
    if not кир or not лат:
        return слово
    таблица = ОМОГЛИФЫ_В_КИРИЛЛИЦУ if кир > лат else ОМОГЛИФЫ_В_ЛАТИНИЦУ
    return слово.translate(таблица)


def очистить(фраза: str) -> str | None:
    """Фраза, пригодная в эталон, или None. Причины отказа перечислены в коде."""
    текст = unicodedata.normalize("NFC", фраза).strip()
    for что, на_что in ЗАМЕНЫ.items():
        текст = текст.replace(что, на_что)
    текст = " ".join(текст.split())
    if not текст:
        return None
    # Цифры распознавание не выдаёт никогда — фразам с ними в эталоне не место.
    if ЦИФРА.search(текст):
        return None
    if set(текст.lower()) - РАЗРЕШЕНО:
        return None
    # Дефис между буквами — законный; висящий на краю слова — мусор разметки.
    if re.search(r"(^|\s)-|-(\s|$)", текст):
        return None
    # Кириллица и латиница внутри одного куска слова — почти всегда перевранная
    # кодировка. В английском корпусе Лейпцига типографские кавычки местами
    # прочитаны как кириллица ещё до упаковки: «тАЬperfectly healthyтАЭ». Буквы
    # при этом законные, и все прочие проверки такое пропускают. Дефис делит
    # слово: «Zoom-конференция» — нормальное слово, а не порча.
    почищенные = []
    for слово in текст.split():
        куски = [починить_омоглифы(к) for к in слово.split(ДЕФИС)]
        for кусок in куски:
            if КИРИЛЛИЦА.search(кусок) and ЛАТИНИЦА.search(кусок):
                return None
        почищенные.append(ДЕФИС.join(куски))
    текст = " ".join(почищенные)
    слова = текст.split()
    if not МИН_СЛОВ <= len(слова) <= МАКС_СЛОВ:
        return None
    # Оборванная фраза учит модель не ставить точку в конце — берём только целые.
    if текст[-1] not in ".!?":
        return None
    if текст[0].islower():      # тоже обрывок: начало предложения потерялось
        return None
    return текст


def письменность_совпадает(текст: str, язык: str) -> bool:
    """Доля слов своей письменности. Считаем по словам, а не по буквам.

    По буквам одно короткое иностранное имя перевешивает: во фразе «Сегодня в
    Astana было тепло» кириллицы 17 знаков против 6 латинских — 0,74, ниже
    порога, хотя своих слов четыре из пяти. Длина слова к языку отношения не имеет.
    """
    свои = чужие = 0
    for слово in текст.split():
        кир, лат = len(КИРИЛЛИЦА.findall(слово)), len(ЛАТИНИЦА.findall(слово))
        if not кир and not лат:
            continue
        своё = кир > лат if ПИСЬМЕННОСТЬ[язык] == "cyr" else лат > кир
        свои += своё
        чужие += not своё
    if not свои + чужие:
        return False
    return свои / (свои + чужие) >= ПОРОГ_ПИСЬМЕННОСТИ


def читать(язык: str) -> tuple[list[str], Counter]:
    папка = СЫРЬЁ / НАБОРЫ[язык]
    файл = папка / f"{НАБОРЫ[язык]}-sentences.txt"
    отказы = Counter()
    готовые, виденные = [], set()
    for строка in файл.read_text(encoding="utf-8").splitlines():
        _, _, фраза = строка.partition("\t")
        if not фраза:
            отказы["без текста"] += 1
            continue
        чистая = очистить(фраза)
        if чистая is None:
            отказы["не прошла очистку"] += 1
            continue
        if not письменность_совпадает(чистая, язык):
            отказы["чужая письменность"] += 1
            continue
        ключ = чистая.lower()
        if ключ in виденные:
            отказы["дубль"] += 1
            continue
        виденные.add(ключ)
        готовые.append(чистая)
    return готовые, отказы


def эталонные_фразы() -> set:
    """FLEURS, если он рядом. Ни одна его фраза не имеет права попасть в обучение.

    Он наша мерная линейка: обучившись на ней, получим красивую цифру и никакого
    знания. Пересечение с новостными корпусами маловероятно, но проверка дешёвая,
    а ошибка неисправима — заметить её будет нечем.
    """
    фразы = set()
    for tsv in ЗДЕСЬ.glob("fleurs_*.tsv"):
        for строка in tsv.read_text(encoding="utf-8").splitlines():
            части = строка.split("\t")
            if len(части) > 3:
                фразы.add(" ".join(части[2].lower().split()))
    return фразы


def selftest() -> None:
    assert очистить("Бұл дұрыс сөйлем болып тұр.") == "Бұл дұрыс сөйлем болып тұр."
    assert очистить("В 2020 году было тепло и сухо.") is None, "цифры должны отсеиваться"
    assert очистить("Слишком коротко.") is None, "короткие фразы не берём"
    assert очистить("Это предложение без точки в конце") is None, "обрывки не берём"
    assert очистить("оборванное начало фразы и точка.") is None, "начало с маленькой — обрывок"
    assert очистить("«Цитата» — это, кстати, важно и нужно.") == "Цитата это, кстати, важно и нужно."
    assert очистить("Слово с мягким пере­носом внутри строки сейчас.") == \
        "Слово с мягким переносом внутри строки сейчас.", "мягкий перенос должен исчезнуть"
    assert очистить("Что-то из-за кого-то опять сломалось тут.") == \
        "Что-то из-за кого-то опять сломалось тут.", "дефисы внутри слов остаются"
    assert очистить("Фраза с - висящим дефисом посреди строки.") is None
    assert очистить("Здесь есть символ ¥ которого нет в алфавите.") is None

    # Перевранная кодировка: кавычки, прочитанные как кириллица. Поймано глазами
    # на готовом наборе, когда все прочие проверки уже проходили.
    assert очистить("He said тАЬperfectly healthyтАЭ about the patient.") is None
    # Омоглифы чинятся, а не выбрасываются: латинская «i» в казахском слове.
    assert очистить("Жiңiшке ауылының тұрғындары осылай көреді.") == \
        "Жіңішке ауылының тұрғындары осылай көреді.", "латинская i должна стать казахской і"
    assert починить_омоглифы("желi") == "желі"
    assert починить_омоглифы("Zoom") == "Zoom", "чистое слово трогать нельзя"
    assert починить_омоглифы("тАЬperfectly") != "тАЬperfectly", "мусор чинить пытаемся"
    assert очистить("Наша Zoom-конференция начнётся ровно в полдень.") == \
        "Наша Zoom-конференция начнётся ровно в полдень.", "дефис делит слово, это не порча"

    assert письменность_совпадает("Бүгін ауа райы жақсы болды.", "kk")
    assert not письменность_совпадает("This sentence is entirely english.", "ru")
    assert письменность_совпадает("Сегодня в Astana было тепло.", "ru"), "вкрапление не повод выбрасывать"
    print("самотест пройден: очистка, цифры, обрывки, типографика, дефисы, письменность")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--seed", type=int, default=20260903)
    a = ap.parse_args()
    if a.selftest:
        selftest()
        return 0

    эталон = эталонные_фразы()
    print(f"фраз мерной линейки под рукой: {len(эталон)}", flush=True)

    собрано = {}
    for язык in НАБОРЫ:
        фразы, отказы = читать(язык)
        было = len(фразы)
        фразы = [ф for ф in фразы if " ".join(ф.lower().split()) not in эталон]
        if было - len(фразы):
            print(f"  {язык}: выброшено пересечений с мерной линейкой: {было - len(фразы)}")
        собрано[язык] = фразы
        всего = sum(отказы.values()) + было
        print(f"{язык}: годных {было} из {всего} "
              f"({', '.join(f'{k} {v}' for k, v in отказы.most_common())})", flush=True)

    # Пропорция считается от самого бедного из двух главных языков: английский
    # добирается до своей доли, а не тянет остальных вниз.
    основа = min(len(собрано["kk"]), len(собрано["ru"]))
    сколько = {я: int(основа / ДОЛЯ["kk"] * ДОЛЯ[я]) for я in ДОЛЯ}
    сколько = {я: min(n, len(собрано[я])) for я, n in сколько.items()}
    print("\nберём:", ", ".join(f"{я} {n}" for я, n in сколько.items()))

    rnd = random.Random(a.seed)
    записи = []
    for язык, n in сколько.items():
        выбор = собрано[язык][:]
        rnd.shuffle(выбор)
        записи += [{"text": ф, "lang": язык} for ф in выбор[:n]]
    rnd.shuffle(записи)

    # Малая проверочная часть — следить за ходом обучения. Настоящий экзамен
    # принимает FLEURS, которого здесь нет ни строкой.
    граница = max(1, len(записи) // 50)
    ГОТОВО.mkdir(parents=True, exist_ok=True)
    for имя, часть in (("dev", записи[:граница]), ("train", записи[граница:])):
        путь = ГОТОВО / f"{имя}.jsonl"
        with путь.open("w", encoding="utf-8") as f:
            for запись in часть:
                f.write(json.dumps(запись, ensure_ascii=False) + "\n")
        доли = Counter(з["lang"] for з in часть)
        print(f"{путь.name}: {len(часть)} фраз, {путь.stat().st_size / 1e6:.1f} МБ, "
              f"{dict(доли)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
