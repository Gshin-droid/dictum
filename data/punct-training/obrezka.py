# -*- coding: utf-8 -*-
"""Обрезка словаря большой модели: выбрасываем то, чего распознавание не выдаёт.

Три четверти веса модели — это таблица «кусочек слова → вектор из 768 чисел» на
250 002 строки, набранная под сотню языков. Наше распознавание выдаёт 71 знак:
латиница, кириллица, казахские буквы, апостроф. Кусочек, в котором есть хоть
один знак вне этого алфавита — иероглиф, арабская вязь, диакритика, цифра, — на
вход не попадёт никогда: разбивщику его просто не из чего собрать. Строку такого
кусочка выбрасываем целиком.

Это не сжатие с потерями: оставшиеся строки не меняются ни на йоту, а выброшены
только недостижимые. Правило намеренно грубое — «достижим в принципе», а не
«встретился в нашем корпусе». Обрезка по корпусу давала файл вдвое легче, но
теряла 0,9 пункта на казахском: в FLEURS нашлись слова, которых в корпусе нет,
и они распадались на буквы. Экономия того не стоила.

    python obrezka.py            # обрезать модель, положить рядом
    python obrezka.py --selftest # проверка на игрушечных данных
"""

import argparse
import sys
from pathlib import Path

import numpy as np

ЗДЕСЬ = Path(__file__).resolve().parent
ТАБЛИЦА = "bert_model.embeddings.word_embeddings.weight"
СЛУЖЕБНЫЕ = 4  # <s>, <pad>, </s>, <unk> — их номера зашиты в самой модели
НАЧАЛО_СЛОВА = "\u2581"  # значок пробела в словаре sentencepiece

sys.path.insert(0, str(ЗДЕСЬ))
from podgotovka import БУКВЫ  # noqa: E402


def достижим(кусочек: str) -> bool:
    """Может ли этот кусочек вообще прийти из распознавания.

    Голый значок начала слова, без единой буквы, — полноправный кусочек словаря
    и приходит постоянно: с него начинается разбивка почти любой фразы. Выбросив
    его как «пустой», я потерял на казахском четыре пункта — модель спотыкалась
    на каждом слове. Отсюда пустое тело здесь законно.
    """
    тело = кусочек.replace(НАЧАЛО_СЛОВА, "").lower()
    return set(тело) <= БУКВЫ


def нужные_номера(sp) -> list[int]:
    """Номера кусочков, которые останутся. Порядок сохраняем — по нему новые номера."""
    нужны = set(range(СЛУЖЕБНЫЕ))
    нужны.update(i for i in range(sp.GetPieceSize()) if достижим(sp.IdToPiece(i)))
    return sorted(нужны)


def обрезать_словарь(протокол: bytes, номера: list[int]) -> bytes:
    """Новый файл разбивщика: те же кусочки в том же порядке, только меньше."""
    from sentencepiece import sentencepiece_model_pb2

    модель = sentencepiece_model_pb2.ModelProto()
    модель.ParseFromString(протокол)
    оставить = [модель.pieces[i] for i in номера]
    del модель.pieces[:]
    модель.pieces.extend(оставить)
    return модель.SerializeToString()


def обрезать_модель(путь_модели: Path, номера: list[int], куда: Path) -> None:
    """Выбрасывает из таблицы векторов строки, до которых не добраться."""
    import onnx
    from onnx import numpy_helper

    модель = onnx.load(str(путь_модели))
    for тензор in модель.graph.initializer:
        if тензор.name == ТАБЛИЦА:
            было = numpy_helper.to_array(тензор)
            стало = np.ascontiguousarray(было[номера])
            тензор.CopyFrom(numpy_helper.from_array(стало, ТАБЛИЦА))
            print(f"таблица векторов: {было.shape} → {стало.shape}")
            break
    else:
        raise SystemExit(f"в модели нет тензора {ТАБЛИЦА} — граф не тот")
    onnx.save(модель, str(куда))


def selftest() -> None:
    """Проверяем то, на чём обрезка может испортить текст незаметно.

    Главное здесь — соответствие номеров: если строки таблицы и кусочки словаря
    разъедутся хоть на единицу, модель продолжит работать и выдавать связный на
    вид текст, только знаки будут ставиться наугад. Молчаливая порча хуже падения.
    """
    class ПоддельныйSP:
        куски = ["<s>", "<pad>", "</s>", "<unk>",
                 "▁мама", "▁мыла", "▁桜", "▁cafē", "▁40", "▁dom", "▁үй", "▁"]

        def GetPieceSize(self): return len(self.куски)
        def IdToPiece(self, i): return self.куски[i]

    номера = нужные_номера(ПоддельныйSP())
    assert номера == [0, 1, 2, 3, 4, 5, 9, 10, 11], номера
    assert not достижим("▁桜"), "иероглиф недостижим"
    assert not достижим("▁cafē"), "буква с диакритикой недостижима"
    assert not достижим("▁40"), "цифр в алфавите распознавания нет"
    assert достижим("▁үй") and достижим("▁dom"), "свои буквы обязаны остаться"
    # Голый значок начала слова обязан пережить обрезку: на нём стоит разбивка
    # почти любой фразы, и без него казахский терял четыре пункта.
    assert достижим(НАЧАЛО_СЛОВА), "голый значок пробела выбрасывать нельзя"

    таблица = np.arange(12 * 2, dtype=np.float32).reshape(12, 2)
    обрезанная = таблица[номера]
    assert (обрезанная[4] == таблица[4]).all(), "строка уехала от своего кусочка"
    assert (обрезанная[6] == таблица[9]).all(), "порядок строк не совпал с порядком кусочков"
    print("обрезка не путает номера")


def main() -> None:
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--папка", default=r"F:\opyt\xlmr-punct", help="где лежит модель")
    разбор.add_argument("--selftest", action="store_true")
    д = разбор.parse_args()
    if д.selftest:
        selftest()
        return

    import sentencepiece as spm

    папка = Path(д.папка)
    протокол = (папка / "sp.model").read_bytes()
    sp = spm.SentencePieceProcessor(model_proto=протокол)
    номера = нужные_номера(sp)
    print(f"кусочков: {sp.GetPieceSize()} → {len(номера)} ({len(номера) / sp.GetPieceSize():.1%})")

    (папка / "sp-obrezan.model").write_bytes(обрезать_словарь(протокол, номера))
    обрезать_модель(папка / "model.onnx", номера, папка / "model-obrezan.onnx")
    for имя in ("model.onnx", "model-obrezan.onnx"):
        print(f"{имя:<22}{(папка / имя).stat().st_size / 1024 / 1024:.0f} МБ")


if __name__ == "__main__":
    main()
