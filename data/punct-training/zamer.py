# -*- coding: utf-8 -*-
"""Замер расстановки знаков и заглавных на FLEURS.

Звук не нужен: у FLEURS на каждую фразу лежит настоящий текст (со знаками и
заглавными) — из него же делается вход, приведённый к строчным без знаков.
Подаём приведённый, сравниваем с настоящим.

Это мерная линейка для «до» и «после». Отметка «до» от 03.09.2026, русский:
знаки F1 80,3 % (точность 77,5 %, полнота 83,4 %), заглавные 86,9 %,
дословно 35,1 %. Казахский: точка 95,1 %, запятая 63,9 %, заглавные 96,6 %.
Разбор — docs/kazahskiy-modul.md.

    python zamer.py --lang ru          # текущий пунктуатор программы
    python zamer.py --lang kk ru en
    python zamer.py --selftest         # проверка самого счётчика
"""

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from podgotovka import ЗНАКИ, очистить  # noqa: E402  (лежит рядом, в той же папке)

ЗДЕСЬ = Path(__file__).resolve().parent
КОРЕНЬ = ЗДЕСЬ.parents[1]
ХВОСТ = re.compile(f"[{re.escape(''.join(ЗНАКИ))}]+$")
НАЗВАНИЯ = {".": "точка", ",": "запятая", "?": "вопрос", "!": "восклицание",
            ";": "точка с запятой", ":": "двоеточие"}


def знак(слово: str) -> str:
    """Знак после слова. Берём последний: «да!!» и «да!» — одно и то же."""
    найдено = ХВОСТ.search(слово)
    return найдено.group()[-1] if найдено else ""


def тело(слово: str) -> str:
    return ХВОСТ.sub("", слово)


def вход(эталон: str) -> str:
    """То, что выдаёт распознавание: строчные буквы, знаков нет."""
    return " ".join(тело(с).lower() for с in эталон.split())


def сравнить(эталон: str, вышло: str, счёт: Counter) -> bool:
    """Копит числа по одной фразе. False — фраза не считается: слова разошлись.

    Слова обязаны совпасть: пунктуатор их не сочиняет, он только размечает.
    Разошлись — виноват не выбор знака, а поломка, и мешать это в один счёт
    нельзя (иначе поломка спрячется за низким F1).
    """
    э, в = эталон.split(), вышло.split()
    if [тело(с).lower() for с in э] != [тело(с).lower() for с in в]:
        счёт["слова разошлись"] += 1
        return False
    счёт["фраз"] += 1
    счёт["слов"] += len(э)
    for сэ, св in zip(э, в):
        счёт["регистр верен"] += тело(сэ) == тело(св)
        зэ, зв = знак(сэ), знак(св)
        if зэ:
            счёт[f"в эталоне {зэ}"] += 1
        if зэ and зэ == зв:
            счёт["угадано"] += 1
            счёт[f"угадано {зэ}"] += 1
        else:
            счёт["пропущено"] += bool(зэ)
            счёт["лишнее"] += bool(зв)
            if зв:
                счёт[f"лишних {зв}"] += 1
    счёт["дословно"] += эталон == вышло
    return True


def фразы(язык: str) -> list[str]:
    """Пригодные эталонные фразы FLEURS: без цифр, без дефисов, целые.

    Отбор тот же, что и в подготовке обучающего материала, плюс дефис: его нет
    в алфавите распознавания, и разбивщик пунктуатора о него спотыкается —
    считать по фразам, которых программе не встретить, значит мерить не то.
    """
    tsv = ЗДЕСЬ / f"fleurs_{ {'kk': 'kk_kz', 'ru': 'ru', 'en': 'en_us'}[язык] }_test.tsv"
    готовые, виденные = [], set()
    for строка in tsv.read_text(encoding="utf-8").splitlines():
        части = строка.split("\t")
        if len(части) < 3:
            continue
        чистая = очистить(части[2])
        if чистая is None or "-" in чистая:
            continue
        if чистая.lower() in виденные:   # одна фраза начитана разными дикторами
            continue
        виденные.add(чистая.lower())
        готовые.append(чистая)
    return готовые


def отчёт(язык: str, счёт: Counter) -> None:
    всего = счёт["фраз"]
    if not всего:
        print(f"{язык}: считать нечего")
        return
    угадано, лишнее, пропущено = счёт["угадано"], счёт["лишнее"], счёт["пропущено"]
    точность = угадано / (угадано + лишнее) if угадано + лишнее else 0.0
    полнота = угадано / (угадано + пропущено) if угадано + пропущено else 0.0
    f1 = 2 * точность * полнота / (точность + полнота) if точность + полнота else 0.0
    print(f"\n=== {язык}: {всего} фраз, {счёт['слов']} слов ===")
    if счёт["слова разошлись"]:
        print(f"!! слова разошлись в {счёт['слова разошлись']} фразах — это поломка, не качество")
    print(f"знаки препинания : F1 {f1:.1%} (точность {точность:.1%}, полнота {полнота:.1%})")
    print(f"заглавные буквы  : {счёт['регистр верен'] / счёт['слов']:.1%}")
    print(f"дословно         : {счёт['дословно'] / всего:.1%}")
    print(f"{'знак':<18}{'в эталоне':>10}{'угадано':>9}{'полнота':>9}{'лишних':>8}")
    for з in sorted(НАЗВАНИЯ, key=lambda з: -счёт[f"в эталоне {з}"]):
        было, попал, лишних = счёт[f"в эталоне {з}"], счёт[f"угадано {з}"], счёт[f"лишних {з}"]
        if not (было or лишних):
            continue
        полн = f"{попал / было:.1%}" if было else "—"
        print(f"{НАЗВАНИЯ[з]:<18}{было:>10}{попал:>9}{полн:>9}{лишних:>8}")


def selftest() -> None:
    счёт = Counter()
    assert сравнить("Привет, мир.", "Привет, мир.", счёт)
    assert счёт["угадано"] == 2 and счёт["лишнее"] == 0 and счёт["дословно"] == 1
    счёт = Counter()
    сравнить("Привет, мир.", "привет мир, ", счёт)      # регистр и знаки мимо
    assert счёт["угадано"] == 0, счёт
    assert счёт["пропущено"] == 2 and счёт["лишнее"] == 1, счёт
    assert счёт["регистр верен"] == 1, счёт             # «мир» угадан, «Привет» нет
    счёт = Counter()
    assert not сравнить("Привет, мир.", "Привет.", счёт)  # слово пропало
    assert счёт["фраз"] == 0 and счёт["слова разошлись"] == 1
    assert вход("Привет, мир!") == "привет мир"
    assert знак("да!!") == "!" and тело("да!!") == "да"
    print("счётчик считает верно")


def main() -> None:
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--lang", nargs="+", default=["ru"], choices=["kk", "ru", "en"])
    разбор.add_argument("--limit", type=int, help="взять только первые N фраз")
    разбор.add_argument("--models", default=str(КОРЕНЬ / "models"))
    разбор.add_argument("--selftest", action="store_true")
    д = разбор.parse_args()
    if д.selftest:
        selftest()
        return

    import punctuate
    пунктуатор = punctuate.load(Path(д.models))
    for язык in д.lang:
        счёт = Counter()
        отобранные = фразы(язык)[: д.limit]
        for i, эталон in enumerate(отобранные, 1):
            сравнить(эталон, пунктуатор.apply(вход(эталон)), счёт)
            if i % 50 == 0:
                print(f"{язык}: {i}/{len(отобранные)}", end="\r", flush=True)
        отчёт(язык, счёт)


if __name__ == "__main__":
    main()
